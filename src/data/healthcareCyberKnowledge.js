export function findMatchingHealthcareTopic(promptText = '') {
  const normalized = (promptText || '').toLowerCase();
  
  // Direct topic lookup
  for (const key of Object.keys(HEALTHCARE_CYBER_TOPICS)) {
    const topic = HEALTHCARE_CYBER_TOPICS[key];
    if (topic.keywords.some(kw => normalized.includes(kw.toLowerCase()))) {
      return topic;
    }
  }

  // Check general healthcare keywords
  if (normalized.includes('בית חולים') || normalized.includes('רפואי') || normalized.includes('בריאות') || normalized.includes('חולה') || normalized.includes('מחלקה') || normalized.includes('מרפאה')) {
    return HEALTHCARE_CYBER_TOPICS.general_hospital_cyber;
  }

  return null;
}
